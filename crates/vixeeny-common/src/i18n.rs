#[cfg(test)]
mod tests {
    use super::*;

    /// The keys declared in the source of this file (so a key missing from `Key::ALL` is caught).
    fn declared_keys() -> usize {
        let source = include_str!("i18n.rs");
        let start = source.find("pub enum Key {").unwrap_or_default();
        let body = &source[start..];
        let end = body.find("\n}\n").unwrap_or(body.len());
        body[..end]
            .lines()
            .filter(|l| {
                l.starts_with("    ")
                    && !l.starts_with("     ")
                    && !l.trim_start().starts_with("//")
                    && l.trim_end().ends_with(',')
            })
            .count()
    }

    fn placeholders(text: &str) -> Vec<&str> {
        let mut found: Vec<&str> = text
            .split('{')
            .skip(1)
            .filter_map(|rest| rest.split('}').next())
            .collect();
        found.sort_unstable();
        found
    }

    #[test]
    fn every_key_is_listed_and_translated_the_same_way_in_every_language() {
        assert_eq!(
            Key::ALL.len(),
            declared_keys(),
            "a key is missing from Key::ALL"
        );
        for key in Key::ALL {
            let (en, fr) = (tr(*key, Lang::En), tr(*key, Lang::Fr));
            assert!(!en.trim().is_empty(), "{key:?} has no English text");
            assert!(!fr.trim().is_empty(), "{key:?} has no French text");
            assert_eq!(
                placeholders(en),
                placeholders(fr),
                "{key:?}: the placeholders differ between languages"
            );
        }
    }

    #[test]
    fn tags() {
        assert_eq!(Lang::from_tag("fr"), Lang::Fr);
        assert_eq!(Lang::from_tag("fr-FR"), Lang::Fr);
        assert_eq!(Lang::from_tag("fr_CA.UTF-8"), Lang::Fr);
        assert_eq!(Lang::from_tag("en-US"), Lang::En);
        assert_eq!(Lang::from_tag("de"), Lang::En);
        assert_eq!(Lang::from_tag(""), Lang::En);
    }

    #[test]
    fn explicit_setting_wins() {
        assert_eq!(Lang::resolve("fr", Some("en-US")), Lang::Fr);
        assert_eq!(Lang::resolve("auto", Some("fr-FR")), Lang::Fr);
    }
}
